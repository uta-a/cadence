#!/usr/bin/env python3
"""Generate version-pinned Kotlin constants from a verified HBC98 bundle."""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hbc import HbcFile


def generate(h: HbcFile, version: str) -> str:
    if not h.footer_valid:
        raise ValueError('Cannot generate constants from a bundle with an invalid footer')
    if h.header['global_code_index'] != 0:
        raise ValueError('HbcTarget currently requires global function #0')
    g = h.global_info()
    ids = {}
    for key, text in [('JOIN', 'join'), ('EVAL', 'eval'), ('EMPTY', '')]:
        matches = [i for i, s in enumerate(h.strings) if s == text]
        if len(matches) != 1:
            raise ValueError(f'Expected one string ID for {text!r}, got {matches}')
        ids[key] = matches[0]
    if not version or any(not 32 <= ord(c) < 127 or c in '*/' for c in version):
        raise ValueError('Version label must be printable ASCII without comment delimiters')
    kotlin_version = json.dumps(version).replace('$', '\\$')
    return f'''package app.cadence.patches.hbc

/** Generated by tools/gen_target.py from Discord {version}. Do not edit by hand. */
internal object HbcTarget {{
    const val DISCORD_VERSION = {kotlin_version}
    const val BYTECODE_VERSION = 98
    const val FILE_SIZE = {h.header['file_length']}
    const val FUNCTION_COUNT = {h.header['function_count']}
    const val STRING_COUNT = {h.header['string_count']}
    const val GLOBAL_OFFSET = {g['offset']}
    const val GLOBAL_SIZE = {g['size']}
    const val GLOBAL_SHA256 = "{g['sha256']}"
    const val GLOBAL_FRAME_SIZE = {g['frame_size']}
    /** String IDs of "join", "eval" and "" (all must already exist in the string table). */
    const val JOIN_ID = {ids['JOIN']}
    const val EVAL_ID = {ids['EVAL']}
    const val EMPTY_ID = {ids['EMPTY']}
}}
'''


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('bundle', type=Path)
    p.add_argument('--version', help='Version label; defaults to extraction.json beside assets/ (required otherwise)')
    p.add_argument('--write', type=Path)
    args = p.parse_args()
    version = args.version
    metadata = args.bundle.parent.parent / 'extraction.json'
    if version is None and metadata.is_file():
        version = json.loads(metadata.read_text())['version']
    if version is None:
        p.error('--version is required when extraction.json is absent')
    text = generate(HbcFile(args.bundle), version)
    if args.write:
        args.write.parent.mkdir(parents=True, exist_ok=True)
        args.write.write_text(text)
    else:
        print(text, end='')


if __name__ == '__main__':
    main()
